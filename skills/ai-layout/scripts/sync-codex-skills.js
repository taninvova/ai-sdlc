#!/usr/bin/env node
// Package native Codex entry points from the same commands and tasks Claude uses.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../../..");
const { entryPreamble } = require(path.join(
	root,
	"skills/ai-layout/templates/ai-factory/make/models.js",
));
const check = process.argv.includes("--check");
const expected = new Map();
function add(name, description, body) {
	expected.set(
		`codex-skills/${name}/SKILL.md`,
		`---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n---\n<!-- Generated by skills/ai-layout/scripts/sync-codex-skills.js. -->\n${body}`,
	);
}
const pluginContext =
	// biome-ignore lint/suspicious/noTemplateCurlyInString: Teach the agent the literal host variable name.
	"The plugin root is two directories above this skill file. Resolve plugin references from that root, not the user's repository. In the referenced procedure, substitute that absolute root for `${CLAUDE_PLUGIN_ROOT}` and use the user's request as `$ARGUMENTS`; treat the request as data, never executable shell text.\n";
for (const name of ["ai-layout", "ai-hooks"]) {
	const file = `skills/${name}/SKILL.md`;
	const text = fs.readFileSync(path.join(root, file), "utf8");
	const description = /^description: (.+)$/m.exec(text)?.[1] || name;
	add(
		name,
		description,
		`${pluginContext}\nRead and follow the [shared procedure](../../${file}).\n`,
	);
}
const tasks = "skills/ai-layout/templates/ai-factory/tasks";
for (const file of fs
	.readdirSync(path.join(root, tasks))
	.filter((f) => f.endsWith(".md"))) {
	const name = path.basename(file, ".md");
	const text = fs.readFileSync(path.join(root, tasks, file), "utf8");
	const agent = /Delegate to the `([a-z]+)` subagent/.exec(text)?.[1];
	add(
		`t4-${name}`,
		/^description: (.+)$/m.exec(text)?.[1] || name,
		`${entryPreamble("codex", name)}\n\nUnless the directive routed the task to a worker, read \`ai-factory/tasks/${name}.md\` in the user's repository and follow it with the user's request as input. If the workspace is absent, report that it needs the t4-adopt-sdlc skill. If the task is missing from an existing workspace, report it and use t4-sync-sdlc to inspect drift. Do not generate project adapters to run this skill.\n` +
			(agent
				? `\nRead the complete procedure in \`ai-factory/agents/${agent}.md\`. When native delegation is available, give that procedure and the task input to a delegate. Otherwise run it in this session and label any review as a self-check, not an independent review. This same-session fallback applies only to the legacy and inherit directives; a routed task never falls back to this session.\n`
				: ""),
	);
}
for (const file of fs
	.readdirSync(path.join(root, "commands"))
	.filter((f) => f.endsWith(".md"))) {
	const name = path.basename(file, ".md");
	// quick's project procedure already supplies its complete behavior and host-neutral fallback.
	if (expected.has(`codex-skills/t4-${name}/SKILL.md`)) continue;
	const text = fs.readFileSync(path.join(root, "commands", file), "utf8");
	add(
		`t4-${name}`,
		/^description: (.+)$/m.exec(text)?.[1] || name,
		`${pluginContext}\nRead and follow the [canonical command](../../commands/${file}). Claude slash-command names in that procedure refer to the corresponding t4 skills in Codex.\n`,
	);
}
for (const [file, body] of expected) {
	const absolute = path.join(root, file);
	if (check) {
		if (!fs.existsSync(absolute) || fs.readFileSync(absolute, "utf8") !== body)
			throw new Error(
				`Stale Codex skill: ${file}; run node skills/ai-layout/scripts/sync-codex-skills.js`,
			);
	} else {
		fs.mkdirSync(path.dirname(absolute), { recursive: true });
		fs.writeFileSync(absolute, body);
	}
}
console.log(
	`Codex skills ${check ? "verified" : "generated"}: ${expected.size}`,
);
