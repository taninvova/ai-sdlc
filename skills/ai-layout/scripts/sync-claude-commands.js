#!/usr/bin/env node
// Claude discovers commands only in commands/, not in the adopted task directory.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../../..");
const { entryPreamble } = require(path.join(
	root,
	"skills/ai-layout/templates/ai-factory/make/models.js",
));
const tasks = path.join(root, "skills/ai-layout/templates/ai-factory/tasks");
const check = process.argv.includes("--check");
let count = 0;
for (const file of fs
	.readdirSync(tasks)
	.filter((name) => name.endsWith(".md"))) {
	// quick already has a native command with its own tool permissions and input prompt.
	if (file === "quick.md") continue;
	const task = fs.readFileSync(path.join(tasks, file), "utf8");
	const description = /^description: (.+)$/m.exec(task)?.[1];
	const hint = /^argument-hint: (.+)$/m.exec(task)?.[1];
	if (!description) throw new Error(`Task has no description: ${file}`);
	const body = `---\ndescription: ${description}\n${hint ? `argument-hint: ${hint}\n` : ""}---\n<!-- Generated by skills/ai-layout/scripts/sync-claude-commands.js. -->\n${entryPreamble("claude", path.basename(file, ".md"))}\n\nUnless the directive routed the task to a worker, read \`ai-factory/tasks/${file}\` in the user's repository and follow it with the request below.\nIf the workspace is absent, report that it needs \`/t4:adopt-sdlc\`; do not silently create one.\nIf this task is missing from an existing workspace, report the missing file and\n\`/t4:sync-sdlc\` drift inspection. Do not generate project adapters to run this command.\n\nTask input: $ARGUMENTS\n`;
	const target = path.join(root, "commands", file);
	if (check) {
		if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== body)
			throw new Error(
				`Missing or stale Claude command: ${file}; run node skills/ai-layout/scripts/sync-claude-commands.js`,
			);
	} else fs.writeFileSync(target, body);
	count++;
}
console.log(
	`Claude task command wrappers ${check ? "verified" : "generated"}: ${count}`,
);
