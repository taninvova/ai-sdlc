#!/usr/bin/env node
// Claude discovers commands only in commands/, not in the adopted task directory.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../../..");
const {
	entryPreamble,
	aliasNotice,
	TASK_ALIASES,
	TASK_SHORTCUTS,
} = require(path.join(
	root,
	"skills/ai-layout/templates/ai-factory/make/models.js",
));
const tasks = path.join(root, "skills/ai-layout/templates/ai-factory/tasks");
const check = process.argv.includes("--check");
let count = 0;
function emit(file, body) {
	const target = path.join(root, "commands", file);
	if (check) {
		if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== body)
			throw new Error(
				`Missing or stale Claude command: ${file}; run node skills/ai-layout/scripts/sync-claude-commands.js`,
			);
	} else fs.writeFileSync(target, body);
	count++;
}
function wrapper(description, hint, preamble, task) {
	return `---\ndescription: ${description}\n${hint ? `argument-hint: ${hint}\n` : ""}---\n<!-- Generated by skills/ai-layout/scripts/sync-claude-commands.js. -->\n${preamble}\n\nUnless the directive routed the task to a worker, read \`ai-factory/tasks/${task}.md\` in the user's repository and follow it with the request below.\nIf the workspace is absent, report that it needs \`/fc:adopt-sdlc\`; do not silently create one.\nIf this task is missing from an existing workspace, report the missing file and\n\`/fc:sync-sdlc\` drift inspection. Do not generate project adapters to run this command.\n\nTask input: $ARGUMENTS\n`;
}
const taskFiles = fs
	.readdirSync(tasks)
	.filter((name) => name.endsWith(".md"));
// A task file named like a deprecated or shortcut entry point would shadow that plugin command.
// Refuse before writing anything, so a clash leaves commands/ as it was.
for (const file of taskFiles) {
	const name = path.basename(file, ".md");
	if (Object.hasOwn(TASK_ALIASES, name))
		throw new Error(
			`Task ${file} uses the deprecated name of ${TASK_ALIASES[name]}; rename the task file`,
		);
	if (Object.hasOwn(TASK_SHORTCUTS, name))
		throw new Error(
			`Task ${file} uses the shortcut name of ${TASK_SHORTCUTS[name]}; rename the task file`,
		);
}
for (const file of taskFiles) {
	// quick already has a native command with its own tool permissions and input prompt.
	if (file === "quick.md") continue;
	const name = path.basename(file, ".md");
	const task = fs.readFileSync(path.join(tasks, file), "utf8");
	const description = /^description: (.+)$/m.exec(task)?.[1];
	const hint = /^argument-hint: (.+)$/m.exec(task)?.[1];
	if (!description) throw new Error(`Task has no description: ${file}`);
	emit(file, wrapper(description, hint, entryPreamble("claude", name), name));
}
// A deprecated task name (models.js TASK_ALIASES) keeps a thin command that says it is deprecated
// and runs the task it now names: the same routing, task file and input.
for (const [alias, name] of Object.entries(TASK_ALIASES)) {
	const task = fs.readFileSync(path.join(tasks, `${name}.md`), "utf8");
	const hint = /^argument-hint: (.+)$/m.exec(task)?.[1];
	emit(
		`${alias}.md`,
		wrapper(
			`Deprecated — use /fc:${name}. Runs the ${name} task under its old name`,
			hint,
			`${aliasNotice("claude", alias)}\n\n${entryPreamble("claude", name)}`,
			name,
		),
	);
}
// A shortcut (models.js TASK_SHORTCUTS) is a stable second name, not a deprecated one: its command
// runs the target task with the target's own preamble and hint, and carries no notice.
for (const [shortcut, name] of Object.entries(TASK_SHORTCUTS)) {
	const task = fs.readFileSync(path.join(tasks, `${name}.md`), "utf8");
	const description = /^description: (.+)$/m.exec(task)?.[1];
	const hint = /^argument-hint: (.+)$/m.exec(task)?.[1];
	if (!description) throw new Error(`Task has no description: ${name}.md`);
	emit(
		`${shortcut}.md`,
		wrapper(
			`Shortcut for /fc:${name} — ${description}`,
			hint,
			entryPreamble("claude", name),
			name,
		),
	);
}
console.log(
	`Claude task command wrappers ${check ? "verified" : "generated"}: ${count}`,
);
